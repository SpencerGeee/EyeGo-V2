#!/usr/bin/env node
'use strict';

/**
 * Inlines the apps' own 3D minibus into the public tracking page.
 *
 * The page is a single HTML file served without a bundler, so it cannot import
 * packages/maps. This transpiles the model math (engine.ts → projectModel and
 * the mesh builders, models.ts → minibus) and writes it between the
 * `model3d:begin` / `model3d:end` markers in public/tracking/index.html, so the
 * bus a rider's family sees in the browser is the bus in the apps.
 *
 * Re-run after changing packages/maps/src/three/{engine,models}.ts:
 *   node eyego-api/scripts/build-web-model.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '../..');
const ts = require(require.resolve('typescript', { paths: [root] }));
const page = path.join(__dirname, '../public/tracking/index.html');

const js = ['engine.ts', 'models.ts']
  .map((f) => fs.readFileSync(path.join(root, 'packages/maps/src/three', f), 'utf8'))
  .map((src) => ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2019, module: ts.ModuleKind.ESNext } }).outputText)
  .join('\n')
  .replace(/^import [^;]+;\s*$/gm, '')
  .replace(/^export (?=(function|const|class|let)\b)/gm, '')
  .replace(/^export \{[^}]*\};?\s*$/gm, '');

const block = [
  '<!-- model3d:begin — generated by eyego-api/scripts/build-web-model.js, do not edit -->',
  '<script>',
  'window.EyeGoModel3D = (function () {',
  js.trim(),
  '  return { projectModel, minibus };',
  '})();',
  '</script>',
  '<!-- model3d:end -->',
].join('\n');

const html = fs.readFileSync(page, 'utf8');
const re = /<!-- model3d:begin[\s\S]*?<!-- model3d:end -->/;
if (!re.test(html)) throw new Error('model3d markers missing from tracking/index.html');
fs.writeFileSync(page, html.replace(re, () => block));
console.log(`model3d inlined (${(block.length / 1024).toFixed(1)} KB)`);
